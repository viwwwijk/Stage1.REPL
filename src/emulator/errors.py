"""Исключения, общие для команд эмулятора."""


class CommandError(Exception):
    """Ошибка выполнения команды.

    Текст ошибки может состоять из нескольких строк (по одной на
    каждую неудачную операцию). Поле output хранит вывод, который
    команда успела сформировать до ошибки, — он печатается перед
    сообщением об ошибке.
    """

    def __init__(self, message, output=""):
        """Создать ошибку с текстом message и частичным выводом output."""
        super().__init__(message)
        self.output = output
